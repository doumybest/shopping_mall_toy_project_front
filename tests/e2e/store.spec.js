    await page.getByRole('button', { name: 'カート 1' }).click()
    await page.getByLabel('お届け先氏名').fill('山田 太郎')
    await page.getByLabel('電話番号').fill('090-1234-5678')
    await page.getByLabel('お届け先住所').fill('東京都渋谷区神宮前1-2-3 テストマンション101号')
    if (usePoints) { await page.getByRole('button', { name: 'すべて使う' }).click(); await page.getByLabel('テスト決済方法').selectOption('MOCK_PAY') }
