import { test, expect } from '@playwright/test'

test('日本語の認証・購入・ポイント・キャンセル', async ({ page }) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'デイリーセラミックマグ', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'ログイン / 新規登録' }).click()
  await page.getByRole('button', { name: 'はじめての方 · 新規登録' }).click()
  await page.getByLabel('お名前', { exact: true }).fill('ブラウザーテスター')
  const email = `e2e-${Date.now()}@test.example`
  await page.getByLabel('メールアドレス', { exact: true }).fill(email)
  await expect(page.getByRole('button', { name: '会員登録する' })).toBeDisabled()
  await page.getByRole('button', { name: '認証コードを送信' }).click()
  await expect(page.getByRole('status')).toContainText('認証コードを送信しました')
  const response = await page.request.get(`http://127.0.0.1:18081/mail?email=${encodeURIComponent(email)}`)
  expect(response.ok()).toBeTruthy()
  const { code } = await response.json()
  await page.getByLabel('メール認証コード', { exact: true }).fill(code === '000000' ? '000001' : '000000')
  await page.getByRole('button', { name: '認証コードを確認' }).click()
  await expect(page.getByRole('alert')).toContainText('認証コードが一致しません')
  await page.getByLabel('メール認証コード', { exact: true }).fill(code)
  await page.getByRole('button', { name: '認証コードを確認' }).click()
  await expect(page.getByRole('status')).toContainText('メール認証が完了しました')
  await expect(page.getByRole('button', { name: '会員登録する' })).toBeEnabled()
  await page.screenshot({ path: '.test-results/signup-email.png', fullPage: true })
  await page.getByLabel('パスワード', { exact: true }).fill('Member-E2E!12345')
  await page.getByLabel('パスワード（確認）', { exact: true }).fill('Member-E2E!12345')
  await page.getByRole('button', { name: '会員登録する' }).click()
  await expect(page.getByRole('status')).toContainText('会員登録が完了')
  await expect(page.getByRole('link', { name: '商品管理', exact: true })).toHaveCount(0)
  await page.goto('/admin/products')
  await expect(page).toHaveURL(/\/forbidden$/)
  await expect(page.getByRole('heading', { name: 'アクセス権限がありません。' })).toBeVisible()
  await page.getByRole('link', { name: 'すべての商品', exact: true }).click()
  const mug = page.locator('.product-card').filter({ has: page.getByRole('button', { name: 'デイリーセラミックマグ', exact: true }) })
  await mug.getByRole('button', { name: 'デイリーセラミックマグ をお気に入りに追加' }).click()
  await expect(mug.getByRole('button', { name: 'デイリーセラミックマグ をお気に入りに追加' })).toHaveAttribute('aria-pressed', 'true')
  await mug.getByRole('button', { name: 'カートに追加' }).click()
  await expect(page.getByRole('status')).toContainText('カートに追加しました')
  await page.reload()
  await expect(page.getByRole('button', { name: 'カート 1' })).toBeVisible()
  async function buy(usePoints = false) {
    await page.getByRole('button', { name: 'カート 1' }).click()
    await page.getByLabel('お届け先氏名').fill('山田 太郎')
    await page.getByLabel('電話番号').fill('090-1234-5678')
    await page.getByLabel('お届け先住所').fill('東京都渋谷区神宮前1-2-3 テストマンション101号')
    if (usePoints) { await page.getByRole('button', { name: 'すべて使う' }).click(); await page.getByLabel('テスト決済方法').selectOption('MOCK_PAY') }
    await page.getByRole('checkbox').check()
    await page.getByRole('button', { name: 'テスト決済で注文する' }).click()
    await expect(page.getByRole('status')).toContainText('テスト決済が完了')
  }
  await buy()
  await expect(page.locator('.order-card')).toHaveCount(1)
  await expect(page.locator('.order-card')).toContainText('￥1,800')
  await page.getByRole('link', { name: 'マイページ', exact: true }).click()
  await expect(page.locator('.point-banner strong')).toContainText('18')
  await expect(page.getByRole('table')).toContainText('購入による獲得')
  await page.getByRole('link', { name: 'すべての商品', exact: true }).click()
  await page.getByRole('button', { name: 'デイリーセラミックマグ', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(page).toHaveURL(/\/products\/\d+$/)
  await page.reload()
  await expect(dialog).toBeVisible()
  await dialog.getByLabel('レビュー', { exact: true }).fill('購入後のテストレビューです。')
  await dialog.getByRole('button', { name: 'レビューを投稿' }).click()
  await expect(dialog.locator('.review')).toContainText('購入後のテストレビューです。')
  await dialog.getByRole('button', { name: '商品詳細を閉じる' }).click()
  await mug.getByRole('button', { name: 'カートに追加' }).click()
  await expect(page.getByRole('status')).toContainText('カートに追加しました')
  await buy(true)
  await expect(page.locator('.order-card')).toHaveCount(2)
  await expect(page.locator('.order-card').first()).toContainText('￥1,782')
  await page.locator('.order-card').first().getByRole('button', { name: '注文をキャンセル', exact: true }).click()
  await page.getByRole('button', { name: 'キャンセルを確定' }).click()
  await expect(page.locator('.order-card').first().locator('.badge')).toContainText('キャンセル済み')
  await page.getByRole('link', { name: 'マイページ', exact: true }).click()
  await expect(page.locator('.point-banner strong')).toContainText('18')
  await expect(page.getByRole('table')).toContainText('利用ポイント返還')
  await expect(page.getByRole('table')).toContainText('キャンセルによる獲得取消')
  await page.getByRole('link', { name: 'すべての商品', exact: true }).click()
  await page.screenshot({ path: '.test-results/store-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(mug).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '.test-results/store-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})

test('管理者の商品登録・編集・販売終了', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'ログイン / 新規登録' }).click()
  await page.getByLabel('メールアドレス', { exact: true }).fill('e2e-admin@test.example')
  await page.getByLabel('パスワード', { exact: true }).fill('E2E-Admin!12345')
  await page.getByRole('button', { name: 'ログイン', exact: true }).click()
  await expect(page.getByRole('link', { name: '商品管理', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '商品管理', exact: true }).click()
  await page.getByLabel('商品名', { exact: true }).fill('E2E 新商品')
  await page.getByLabel('価格（円）').fill('12000')
  await page.getByLabel('在庫数（個）').fill('7')
  await page.getByLabel('商品説明').fill('管理者テスト商品説明')
  await page.getByRole('button', { name: '商品を登録', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: 'E2E 新商品' })
  await expect(row).toContainText('￥12,000')
  await row.getByRole('button', { name: '編集', exact: true }).click()
  await page.getByLabel('価格（円）').fill('15000')
  await page.getByRole('button', { name: '変更を保存' }).click()
  await expect(row).toContainText('￥15,000')
  await row.getByRole('button', { name: '削除', exact: true }).click()
  await row.getByRole('button', { name: '削除を確定' }).click()
  await expect(row).toHaveCount(0)
})


test('URLの直接入力・認証ガード・履歴移動・404', async ({ page }) => {
  await page.goto('/cart')
  await expect(page).toHaveURL(/\/login\?redirect=/)
  await page.getByLabel('メールアドレス', { exact: true }).fill('e2e-admin@test.example')
  await page.getByLabel('パスワード', { exact: true }).fill('Incorrect-password!123')
  await page.getByRole('button', { name: 'ログイン', exact: true }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page).toHaveURL(/\/login\?redirect=/)
  await page.getByLabel('パスワード', { exact: true }).fill('E2E-Admin!12345')
  await page.getByRole('button', { name: 'ログイン', exact: true }).click()
  await expect(page).toHaveURL('http://localhost:5174/cart')
  await page.getByRole('link', { name: '注文履歴', exact: true }).click()
  await expect(page).toHaveURL('http://localhost:5174/orders')
  await page.goBack()
  await expect(page).toHaveURL('http://localhost:5174/cart')
  await page.goForward()
  await expect(page).toHaveURL('http://localhost:5174/orders')
  await page.reload()
  await expect(page).toHaveURL('http://localhost:5174/orders')
  await expect(page.getByRole('heading', { name: '注文履歴', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'ログアウト', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  await page.goto('/products/99999999')
  await expect(page.getByRole('heading', { name: '商品が見つかりません。' })).toBeVisible()
  await page.goto('/this-page-does-not-exist')
  await expect(page.getByRole('heading', { name: 'ページが見つかりません。' })).toBeVisible()
  await page.goto('/login?redirect=https://example.com')
  await page.getByLabel('メールアドレス', { exact: true }).fill('e2e-admin@test.example')
  await page.getByLabel('パスワード', { exact: true }).fill('E2E-Admin!12345')
  await page.getByRole('button', { name: 'ログイン', exact: true }).click()
  await expect(page).toHaveURL('http://localhost:5174/')
})
